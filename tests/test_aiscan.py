ZWSP, ZWNJ = chr(0x200B), chr(0x200C)


def zw_encode(msg: str) -> str:
    bits = "".join(format(ord(c), "08b") for c in msg)
    return "".join(ZWSP if b == "0" else ZWNJ for b in bits)


def tag_encode(msg: str) -> str:
    return "".join(chr(0xE0000 + ord(c)) for c in msg)


def vs_encode(data: bytes) -> str:
    return "".join(chr(0xFE00 + b) if b < 16 else chr(0xE0100 + b - 16) for b in data)


def ids(findings):
    return {f.rule_id for f in findings}


class TestAttribution(unittest.TestCase):
    def scan(self, text, ext=".py"):
        return textscan.scan_text("x" + ext, text, ext=ext)[0]

    def test_claude_code_footer(self):
        f = self.scan("# Generated with [Claude Code](https://claude.ai/code)")
        self.assertIn("AI-ATTR-001", ids(f))
        self.assertIn("AI-ATTR-004", ids(f))

    def test_coauthor_trailer(self):
        f = self.scan("Co-Authored-By: Claude <noreply@anthropic.com>")
        self.assertIn("AI-ATTR-003", ids(f))
        self.assertIn("AI-ATTR-002", ids(f))

    def test_other_agents(self):
        for line, rid in [
            ("Co-authored-by: Cursor <agent@cursor.com>", "AI-ATTR-006"),
            ("# This file was generated by an AI assistant", "AI-ATTR-008"),
            ("// created with GitHub Copilot", "AI-ATTR-009"),
            ("<!-- AI-generated content -->", "AI-ATTR-010"),
        ]:
            with self.subTest(line=line):
                self.assertIn(rid, ids(self.scan(line)))

    def test_assistant_leak(self):
        f = self.scan("# As an AI language model, I cannot execute this code")
        self.assertIn("AI-LEAK-001", ids(f))

    def test_chat_template_tokens(self):
        f = self.scan("prompt = '<|im_start|>system'")
        self.assertIn("AI-LEAK-009", ids(f))

    def test_elision_placeholder(self):
        f = self.scan("    # ... rest of the implementation remains unchanged")
        self.assertTrue({"AI-PH-001", "AI-PH-002"} & ids(f))

    def test_clean_file_has_no_findings(self):
        code = "def topla(a, b):\n    return a + b\n\nprint(topla(2, 3))\n"
        self.assertEqual(self.scan(code), [])

    def test_markdown_fences_skipped_in_md(self):
        self.assertNotIn("AI-LEAK-013", ids(self.scan("```python", ext=".md")))
        self.assertIn("AI-LEAK-013", ids(self.scan("```python", ext=".py")))


class TestHiddenUnicode(unittest.TestCase):
    def test_tag_chars_decoded(self):
        f = unicodescan.scan_unicode("a.py", "x = 1" + tag_encode("Claude Code"))
        hit = [x for x in f if x.rule_id == "AI-UNI-001"]
        self.assertTrue(hit)
        self.assertIn("Claude Code", hit[0].detail)

    def test_zero_width_binary_decoded(self):
        f = unicodescan.scan_unicode("a.py", "kod" + zw_encode("AI2026"))
        hit = [x for x in f if x.rule_id == "AI-UNI-003"]
        self.assertTrue(hit)
        self.assertIn("AI2026", hit[0].detail)

    def test_variation_selector_decoded(self):
        f = unicodescan.scan_unicode("a.md", "merhaba \U0001F600" + vs_encode(b"gizli"))
        hit = [x for x in f if x.rule_id == "AI-UNI-002"]
        self.assertTrue(hit)
        self.assertIn("gizli", hit[0].detail)

    def test_bidi_control(self):
        f = unicodescan.scan_unicode("a.js", "if (admin" + chr(0x202E) + ") {")
        self.assertIn("AI-UNI-004", ids(f))

    def test_homoglyph(self):
        f = unicodescan.scan_unicode("a.py", "pass" + chr(0x0430) + "word = 1")
        self.assertIn("AI-UNI-007", ids(f))

    def test_soft_hyphen(self):
        f = unicodescan.scan_unicode("a.txt", "nor" + chr(0x00AD) + "mal metin")
        self.assertIn("AI-UNI-005", ids(f))

    def test_clean_text_no_unicode_findings(self):
        self.assertEqual(unicodescan.scan_unicode("a.py", "def f():\n    return 42\n"), [])

    def test_turkish_text_is_clean(self):
        text = "def hesapla():\n    # kabin ölçüsü şudur: ağırlık ve genişlik\n    return 1\n"
        self.assertEqual(unicodescan.scan_unicode("a.py", text), [])

    def test_legitimate_unicode_is_not_flagged(self):
        """Gercek depolarda cikan mesru kullanimlar bulgu uretmemeli."""
        temiz = [
            "// hesap: sin\u03b8 + cos\u03b8 = 1",              # matematik notasyonu
            "double \u03b1 = 0.5;",                             # Yunan harfi degisken
            "label = '\U0001F468\u200d\U0001F469\u200d\U0001F467'",  # emoji ZWJ dizisi
            "var \u0441\u0435\u0440\u0438\u0430\u043b\u0438\u0437\u0430\u0442\u043e\u0440xdto = 1;",  # Rusca+Latin tanimlayici
            "# \u043f\u0440\u0438\u0432\u0435\u0442 \u043c\u0438\u0440",  # tamami Rusca yorum
        ]
        for text in temiz:
            with self.subTest(text=text[:30]):
                self.assertEqual(unicodescan.scan_unicode("a.js", text), [], text)

    def test_homoglyph_attack_still_caught(self):
        """Cogunlukla Latin bir kelimeye sizdirilmis karakter yakalanmali."""
        for text in ["p" + chr(0x0430) + "ssword = 1",
                     "if user == 'admin" + chr(0x043E) + "'"]:
            with self.subTest(text=text):
                self.assertIn("AI-UNI-007", ids(unicodescan.scan_unicode("a.js", text)))

    def test_excerpt_makes_invisible_visible(self):
        out = unicodescan.safe_excerpt("a" + ZWSP + "b")
        self.assertEqual(out, "a<U+200B>b")


