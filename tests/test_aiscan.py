class TestBinaryMetadata(unittest.TestCase):
    def _png(self, key: bytes, value: bytes) -> bytes:
        def chunk(ctype, payload):
            return (struct.pack(">I", len(payload)) + ctype + payload +
                    struct.pack(">I", zlib.crc32(ctype + payload) & 0xFFFFFFFF))
        return (b"\x89PNG\r\n\x1a\n"
                + chunk(b"IHDR", struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0))
                + chunk(b"tEXt", key + b"\x00" + value)
                + chunk(b"IEND", b""))

    def test_png_text_chunk(self):
        data = self._png(b"Software", b"Stable Diffusion WebUI")
        f = binmeta.scan_binary("a.png", "a.png", data, ".png")
        self.assertIn("AI-META-001", ids(f))

    def test_png_generation_parameters(self):
        data = self._png(b"parameters", b"masterpiece, Steps: 20, Sampler: Euler a")
        f = binmeta.scan_binary("a.png", "a.png", data, ".png")
        self.assertTrue(any("parameters" in x.match for x in f))

    def test_pdf_producer(self):
        data = b"%PDF-1.7\n1 0 obj<</Producer(ChatGPT PDF Export)>>endobj\n"
        f = binmeta.scan_binary("a.pdf", "a.pdf", data, ".pdf")
        self.assertIn("AI-META-006", ids(f))

    def test_generic_binary_marker(self):
        data = b"\x00\x01\x02 built by anthropic claude \xff\xfe"
        f = binmeta.scan_binary("a.bin", "a.bin", data, ".bin")
        self.assertIn("AI-META-010", ids(f))


class TestGitScan(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        r = cls.tmp.name
        env = {**os.environ, "GIT_CONFIG_GLOBAL": "/dev/null", "GIT_CONFIG_SYSTEM": "/dev/null"}
        run = lambda *a: subprocess.run(a, cwd=r, check=True, capture_output=True, env=env)
        try:
            run("git", "init", "-q", "-b", "main")
        except (subprocess.CalledProcessError, FileNotFoundError):
            raise unittest.SkipTest("git yok")
        run("git", "config", "user.name", "Claude")
        run("git", "config", "user.email", "noreply@anthropic.com")
        with open(os.path.join(r, "a.txt"), "w") as fh:
            fh.write("merhaba\n")
        run("git", "add", "a.txt")
        run("git", "commit", "-q", "-m",
            "feat: ilk surum\n\nGenerated with [Claude Code](https://claude.ai/code)\n\n"
            "Co-Authored-By: Claude <noreply@anthropic.com>")

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def test_detects_ai_author_and_message(self):
        f, commits, err = gitscan.scan_git(self.tmp.name)
        self.assertEqual(err, "")
        self.assertEqual(commits, 1)
        found = ids(f)
        self.assertIn("AI-GIT-001", found)      # yazar = Claude
        self.assertIn("AI-GIT-005", found)      # anthropic e-postasi
        self.assertIn("AI-ATTR-001", found)     # mesajdaki imza
        self.assertIn("AI-GIT-007", found)      # depo config'i

    def test_git_artifacts(self):
        f = gitscan.scan_git_artifacts(self.tmp.name)
        self.assertIn("AI-GIT-008", ids(f))


class TestEndToEnd(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = self.tmp.name
        write = lambda name, body: open(
            os.path.join(self.root, name), "w", encoding="utf-8").write(body)
        os.makedirs(os.path.join(self.root, ".claude"), exist_ok=True)
        write("temiz.py", "def kare(x):\n    return x * x\n")
        write("kirli.py",
              "# Generated with Claude Code\n"
              "def f():\n"
              "    pass" + zw_encode("izim") + "\n"
              "    # ... rest of code unchanged\n")
        write("CLAUDE.md", "# Proje talimatlari\n")
        write(".claude/settings.json", "{}\n")
        write("gizli.md", "Baslik" + tag_encode("gizli imza") + "\n")
        write("pragma.py", "# Generated with Claude Code  aiscan:ignore\n")

    def tearDown(self):
        self.tmp.cleanup()

    def _run(self, *extra):
        out = os.path.join(self.root, "r.json")
        rc = main([self.root, "--no-git", "--quiet", "--format", "csv",
                   "--json", out, *extra])
        with open(out, encoding="utf-8") as fh:
            return rc, json.load(fh)

    def test_full_scan(self):
        rc, doc = self._run()
        self.assertEqual(rc, 0)
        rules = doc["ozet"]["kural"]
        self.assertIn("AI-ATTR-001", rules)          # acik imza
        self.assertIn("AI-UNI-003", rules)           # gizli ZW yuku
        self.assertIn("AI-UNI-001", rules)           # TAG karakterleri
        self.assertIn("AI-PATH-001", rules)          # CLAUDE.md + .claude/
        self.assertGreaterEqual(doc["ozet"]["risk_skoru"], 40)
        self.assertEqual(doc["ozet"]["hukum"], "AI IZI DOGRULANDI")

        paths = {b["path"] for b in doc["bulgular"]}
        self.assertNotIn("temiz.py", paths)          # temiz dosya raporlanmaz
        self.assertNotIn("pragma.py", paths)         # aiscan:ignore calisiyor

        decoded = [b["detail"] for b in doc["bulgular"] if b["rule_id"] == "AI-UNI-003"]
        self.assertTrue(any("izim" in d for d in decoded))

    def test_min_severity_filter(self):
        _, doc = self._run("--min-severity", "critical")
        self.assertTrue(all(b["severity"] == "critical" for b in doc["bulgular"]))

    def test_baseline_suppression(self):
        base = os.path.join(self.root, "base.json")
        main([self.root, "--no-git", "--quiet", "--format", "csv", "--write-baseline", base])
        rc, doc = self._run("--baseline", base)
        self.assertEqual(doc["ozet"]["toplam_bulgu"], 0)
        self.assertEqual(doc["ozet"]["hukum"], "TEMIZ")

    def test_fail_on_exit_code(self):
        rc = main([self.root, "--no-git", "--quiet", "--format", "csv", "--fail-on", "critical"])
        self.assertEqual(rc, 1)

    def test_only_rule_filter(self):
        _, doc = self._run("--only", "AI-ATTR-001")
        self.assertTrue(doc["bulgular"])
        self.assertTrue(all(b["rule_id"] == "AI-ATTR-001" for b in doc["bulgular"]))

    def test_report_formats(self):
        opts = walker.Options(root=self.root)
        files = walker.discover(self.root, opts, use_vcs=False)
        res = walker.scan_files(files, opts)
        res.root = self.root
        json.loads(report.render_json(res, res.findings))
        sarif = json.loads(report.render_sarif(res, res.findings))
        self.assertEqual(sarif["version"], "2.1.0")
        html = report.render_html(res, res.findings)
        self.assertIn("<!doctype html>", html)
        self.assertIn("</html>", html)
        self.assertTrue(report.render_markdown(res, res.findings).startswith("# AI Iz"))
        self.assertIn("siddet", report.render_csv(res.findings).splitlines()[0])


class TestEngineInternals(unittest.TestCase):
    def test_non_capturing_conversion(self):
        self.assertEqual(textscan._non_capturing(r"(a)(?:b)\(c\)[(]"), r"(?:a)(?:b)\(c\)[(]")

    def test_master_regex_finds_every_rule(self):
        """Master prefilter hicbir kurali kacirmamali."""
        eng = textscan.get_engine()
        missed = []
        for rule, rx in eng.compiled:
            probe = {
                "AI-ATTR-001": "Generated with Claude Code",
                "AI-LEAK-001": "as an AI language model",
                "AI-PH-003": "# add your code here",
            }.get(rule.id)
            if probe and not eng.candidate_lines(probe):
                missed.append(rule.id)
        self.assertEqual(missed, [])

    def test_per_rule_cap(self):
        text = "\n".join(["# Generated with Claude Code"] * 20)
        f, _ = textscan.scan_text("a.py", text, per_rule_cap=3)
        direct = [x for x in f if x.rule_id == "AI-ATTR-001" and x.line]
        summary = [x for x in f if x.rule_id == "AI-ATTR-001" and not x.line]
        self.assertEqual(len(direct), 3)
        self.assertTrue(summary)


